// Assinatura de release opcional, via variáveis de ambiente (nunca versionar a keystore).
val releaseKeystore: String? = System.getenv("DI_KEYSTORE_PATH")

android {
    namespace = "com.driverintelligence"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.driverintelligence.app"
        minSdk = 29
        targetSdk = 35
        // Cada build do GitHub Actions gera um número de versão maior.
        versionCode = System.getenv("GITHUB_RUN_NUMBER")?.toIntOrNull() ?: 1
        versionName = "0.1.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables { useSupportLibrary = true }
        // Celulares reais são ARM: incluir só essas arquiteturas reduz o APK em ~2/3.
        // Para emulador x86 (testes instrumentados), compile com -PallAbis.
        if (!project.hasProperty("allAbis")) {
            ndk { abiFilters += listOf("arm64-v8a", "armeabi-v7a") }
        }
    }

    signingConfigs {
        // Chave de teste FIXA, versionada no repositório: todo build de teste tem a mesma
        // assinatura, então o Android aceita instalar uma versão nova por cima da anterior.
        getByName("debug") {
            storeFile = file("debug.keystore")
            storePassword = "android"
            keyAlias = "androiddebugkey"
            keyPassword = "android"
        }
        if (releaseKeystore != null) {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = System.getenv("DI_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("DI_KEY_ALIAS")
                keyPassword = System.getenv("DI_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (releaseKeystore != null) signingConfig = signingConfigs.getByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            isReturnDefaultValues = true
        }
    }

    packaging {
        resources { excludes += "/META-INF/{AL2.0,LGPL2.1}" }
    }
}

